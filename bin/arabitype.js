#!/usr/bin/env node
'use strict';
/*
 * arabitype — catch the Arabic-typography mistakes that quietly break Arabic rendering.
 * Part of Otto · dev.ottospace.co. Zero dependencies.
 *
 * Arabic is a connected, cursive script that carries diacritics (tashkeel):
 *  - letter-spacing SHATTERS its ligatures/joins
 *  - tight line-height CRUSHES the diacritics
 *  - small sizes hurt its dense legibility
 *  - text-transform: uppercase is meaningless (Arabic has no case)
 *  - Latin-only fonts render Arabic in an ugly fallback
 * AI codegen (and most Western-trained code) does all five. arabitype flags them.
 */
const fs = require('fs');
const path = require('path');

const VERSION = '0.1.0';
const CODE_EXT = new Set(['.js', '.jsx', '.ts', '.tsx', '.html', '.vue', '.svelte', '.astro']);
const CSS_EXT = new Set(['.css', '.scss', '.less', '.pcss']);
const IGNORE_DIR = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'out', 'coverage', '.turbo', 'vendor', '.svelte-kit']);

function lineOf(src, i) { return src.slice(0, i).split('\n').length; }

// Tailwind utilities that hurt Arabic typography
function twFlag(tok) {
  const u = tok.includes(':') ? tok.slice(tok.lastIndexOf(':') + 1) : tok;
  if (/^-?tracking-(?!normal$)/.test(u)) return 'letter-spacing (tracking-*) shatters Arabic ligatures — remove it for Arabic text';
  if (u === 'leading-none' || u === 'leading-tight' || u === 'leading-snug') return 'line-height too tight — Arabic tashkeel needs leading ≥ 1.5 (use leading-relaxed+)';
  if (u === 'text-xs' || u === 'text-sm') return 'font-size small for Arabic — body Arabic should be ≥ 16px (text-base+)';
  if (u === 'uppercase') return 'text-transform: uppercase has no effect on Arabic and can hide bugs';
  return null;
}

const CLASS_ATTR = /\b(class(?:Name)?)\s*=\s*(?:"([^"]*)"|'([^']*)'|\{\s*(?:"([^"]*)"|'([^']*)'|`([^`]*)`)\s*\})/g;

function scanFile(file, src) {
  const F = [];
  const push = (idx, from, msg) => F.push({ file, line: lineOf(src, idx), from: String(from).trim().slice(0, 48), msg });
  const ext = path.extname(file);
  let m;

  if (CODE_EXT.has(ext)) {
    while ((m = CLASS_ATTR.exec(src))) {
      const raw = m[2] ?? m[3] ?? m[4] ?? m[5] ?? m[6];
      if (raw == null) continue;
      for (const tok of raw.split(/\s+/)) {
        if (!tok || tok.includes('{')) continue;
        const msg = twFlag(tok);
        if (msg) push(m.index, tok, msg);
      }
    }
  }
  if (CSS_EXT.has(ext)) {
    // letter-spacing (non-zero, non-normal)
    const ls = /letter-spacing:\s*([^;]+)/g;
    while ((m = ls.exec(src))) { const v = m[1].trim(); if (!/^(0(px|em|rem|%)?|normal)$/.test(v)) push(m.index, 'letter-spacing: ' + v, 'letter-spacing shatters Arabic ligatures — set 0/normal for Arabic'); }
    // line-height unitless < 1.5
    const lh = /line-height:\s*([0-9]*\.?[0-9]+)\b(?!\s*(px|rem|em|%))/g;
    while ((m = lh.exec(src))) { if (parseFloat(m[1]) < 1.5) push(m.index, 'line-height: ' + m[1], 'line-height ' + m[1] + ' crushes Arabic tashkeel — use ≥ 1.5'); }
    // font-size < 16px
    const fs2 = /font-size:\s*([0-9]+(?:\.[0-9]+)?)px/g;
    while ((m = fs2.exec(src))) { if (parseFloat(m[1]) < 16) push(m.index, 'font-size: ' + m[1] + 'px', 'font-size ' + m[1] + 'px small for Arabic — body ≥ 16px'); }
    // text-transform uppercase
    const tt = /text-transform:\s*uppercase/g;
    while ((m = tt.exec(src))) push(m.index, 'text-transform: uppercase', 'uppercase is meaningless on Arabic (no case) — can hide bugs');
  }
  // Latin-only font stack (both code + css)
  const ff = /font-family:[^;}"']*\b(Inter|Roboto|Helvetica|Arial|system-ui)\b(?![^;}"']*[Aa]rabic)/g;
  while ((m = ff.exec(src))) push(m.index, m[0].slice(0, 40), 'Latin-only font — add an Arabic family (e.g. "Cairo","IBM Plex Sans Arabic")');

  return F;
}

function walk(dir, out = []) {
  for (const name of fs.readdirSync(dir)) {
    if (IGNORE_DIR.has(name) || (name.startsWith('.') && name !== '.')) continue;
    const full = path.join(dir, name);
    let st; try { st = fs.statSync(full); } catch { continue; }
    if (st.isDirectory()) walk(full, out);
    else if (CODE_EXT.has(path.extname(full)) || CSS_EXT.has(path.extname(full))) out.push(full);
  }
  return out;
}

const RULES_DOC = `# Arabic typography rules for AI agents (generated by arabitype)
When styling anything that can hold Arabic text:
1. NEVER apply letter-spacing / Tailwind tracking-* to Arabic — it shatters the cursive joins & ligatures. Keep it 0/normal.
2. Give Arabic room: line-height ≥ 1.5 (never leading-none/tight/snug) so tashkeel (diacritics) don't collide.
3. Arabic body text ≥ 16px (avoid text-xs/text-sm for body).
4. Never text-transform: uppercase on Arabic — it has no case; it does nothing and hides bugs.
5. Use an Arabic-capable font with a real fallback (e.g. "Cairo","IBM Plex Sans Arabic", system-ui) — never a Latin-only stack for Arabic.
`;

const HELP = `arabitype v${VERSION} — catch the Arabic-typography mistakes that break Arabic rendering.
Part of Otto · dev.ottospace.co

Usage:
  npx arabitype [path]            report Arabic-typography issues (default: .)
  npx arabitype [path] --json     machine-readable (CI)
  npx arabitype [path] --init-rules  write ARABIC-TYPE-RULES.md for your AI agent
  npx arabitype --help | --version

It reports, it never edits — typography is judgment. It flags where Arabic would break:
letter-spacing, tight line-height, tiny sizes, uppercase, and Latin-only fonts.`;

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) { console.log(HELP); return; }
  if (args.includes('--version') || args.includes('-v')) { console.log(VERSION); return; }
  const asJson = args.includes('--json');
  const target = args.find(a => !a.startsWith('-')) || '.';

  if (args.includes('--init-rules')) {
    const dest = path.join(target, 'ARABIC-TYPE-RULES.md');
    fs.writeFileSync(dest, RULES_DOC);
    console.log(`✓ wrote ${dest} — point Cursor/Claude at it so they stop breaking Arabic type.`);
    return;
  }

  let files;
  try { files = fs.statSync(target).isDirectory() ? walk(target) : [target]; }
  catch { console.error(`arabitype: cannot read ${target}`); process.exit(2); }

  const byFile = {}; let total = 0;
  for (const file of files) {
    let src; try { src = fs.readFileSync(file, 'utf8'); } catch { continue; }
    const f = scanFile(file, src);
    if (f.length) { byFile[file] = f; total += f.length; }
  }
  const rel = f => path.relative(process.cwd(), f) || f;

  if (asJson) {
    console.log(JSON.stringify({ version: VERSION, files: files.length, findings: total,
      results: Object.entries(byFile).flatMap(([f, arr]) => arr.map(x => ({ ...x, file: rel(f) }))) }, null, 2));
    process.exit(total ? 1 : 0);
  }
  for (const file of Object.keys(byFile)) {
    console.log(`\n\x1b[1m${rel(file)}\x1b[0m`);
    for (const f of byFile[file]) console.log(`  \x1b[35mtype\x1b[0m :${f.line}  ${f.from}  \x1b[2m${f.msg}\x1b[0m`);
  }
  console.log(`\n\x1b[1marabitype v${VERSION}\x1b[0m  ${files.length} files  ·  \x1b[35m${total} Arabic-type issue${total === 1 ? '' : 's'}\x1b[0m`);
  if (!total) console.log('✓ clean — nothing that would break Arabic type.');
  else console.log('→ fix for Arabic text; run \x1b[1m--init-rules\x1b[0m so your AI agent stops adding them.');
  process.exit(total ? 1 : 0);
}

main();
