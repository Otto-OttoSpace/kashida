#!/usr/bin/env node
'use strict';
/*
 * kashida — catch the typography mistakes that quietly break COMPLEX-SCRIPT
 * rendering (Arabic & the RTL-cursive family, Indic, SE-Asian, CJK, Hebrew),
 * but ONLY where such a script is actually in play.
 *
 * Three tiers:
 *   static (default)  AST/PostCSS — letter/word-spacing, tight leading, tiny
 *                     size, uppercase, Latin-only font, ligature-off,
 *                     bidi-override, vertical writing, stray ZWNJ. Zero heavy
 *                     deps, never throws, per-family gating (Hebrew/CJK never
 *                     get a false letter-spacing flag).
 *   --render          HarfBuzz ground truth — shapes the text and reports tofu
 *                     (missing glyphs), fake-Arabic fonts (no joining), and
 *                     unattached marks. Optional dep: harfbuzzjs + fontkit.
 *   --url <URL>       render-time — headless Chromium inspects the live page
 *                     (computed style + the ACTUAL rendered face via CDP +
 *                     downloaded webfonts). Optional dep: playwright + wawoff2;
 *                     falls back to a curl+shape analysis when unavailable.
 *
 * It reports, it never edits — typography is judgment. (Formerly `arabitype`.)
 */
const fs = require('fs');
const path = require('path');
const { scanSource } = require('../lib/kashida-core');

const VERSION = require('../package.json').version;

const CODE_EXT = new Set(['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.html', '.htm', '.vue', '.svelte', '.astro']);
const CSS_EXT = new Set(['.css', '.scss', '.less', '.pcss']);
const IGNORE_DIR = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'out', 'coverage', '.turbo', 'vendor', '.svelte-kit']);

function walk(dir, out = []) {
  let entries;
  try { entries = fs.readdirSync(dir); } catch { return out; }
  for (const name of entries) {
    if (IGNORE_DIR.has(name) || (name.startsWith('.') && name !== '.')) continue;
    const full = path.join(dir, name);
    let st; try { st = fs.statSync(full); } catch { continue; }
    if (st.isDirectory()) walk(full, out);
    else {
      const ext = path.extname(full);
      if (CODE_EXT.has(ext) || CSS_EXT.has(ext)) out.push(full);
    }
  }
  return out;
}

function loadConfig(target) {
  let dir;
  try { dir = fs.statSync(target).isDirectory() ? target : path.dirname(target); }
  catch { dir = process.cwd(); }
  for (const base of [dir, process.cwd()]) {
    for (const name of ['kashida.config.json', '.kashidarc.json', '.kashidarc']) {
      const p = path.join(base, name);
      try { if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8')); } catch {}
    }
  }
  return {};
}

function lineAt(src, index) { let line = 1; for (let i = 0; i < index && i < src.length; i++) if (src[i] === '\n') line++; return line; }

function parseArgs(argv) {
  const o = { _: [], render: false, json: false, check: false, initRules: false, fontFix: false, help: false, version: false, url: null, font: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--render') o.render = true;
    else if (a === '--json') o.json = true;
    else if (a === '--check') o.check = true;
    else if (a === '--init-rules') o.initRules = true;
    else if (a === '--help' || a === '-h') o.help = true;
    else if (a === '--version' || a === '-v') o.version = true;
    else if (a === '--url') o.url = argv[++i];
    else if (a.startsWith('--url=')) o.url = a.slice(6);
    else if (a === '--font-fix') o.fontFix = true;
    else if (a === '--font') o.font = argv[++i];
    else if (a.startsWith('--font=')) o.font = a.slice(7);
    else if (a.startsWith('-')) { /* ignore unknown */ }
    else o._.push(a);
  }
  return o;
}

const RULES_DOC = `# Complex-script typography rules for AI coding agents (generated by kashida)
When styling anything that can hold Arabic / Indic / SE-Asian / CJK / Hebrew text:
1. NEVER apply letter-spacing / word-spacing / Tailwind tracking-* to a CURSIVE (Arabic-family) or COMPLEX (Indic/SE-Asian) script — it shatters the joins / splits conjuncts. Keep it 0/normal. (Hebrew & CJK don't join — spacing there is fine.)
2. Give complex scripts room: line-height ≥ 1.5 (never leading-none/tight/snug) so marks/tashkeel don't collide.
3. Complex-script body text ≥ 16px (avoid text-xs/text-sm for body).
4. Never text-transform: uppercase/capitalize/lowercase on caseless scripts (Arabic/Indic/CJK) — it does nothing and hides bugs.
5. Use a script-capable font with a real fallback (e.g. "Cairo","IBM Plex Sans Arabic", system-ui) — never a Latin-only stack for Arabic.
6. Never disable joining features (font-feature-settings "calt"/"rlig"/"liga"/"init"/"medi"/"fina" 0, font-variant-ligatures:none) on a cursive/complex script.
7. Never unicode-bidi:*-override or writing-mode:vertical-* on RTL text.
8. Don't leave a stray literal ZWNJ (U+200C) inside an Arabic word — it breaks the join.
9. NEVER split cursive/RTL text into per-character elements. Text-animation splitters — GSAP SplitText \`type:"chars"\`, or \`.split('')\` / \`[...text].map(c => <span>)\` — put each Arabic letter in its own <span>/<div>, so it renders in the ISOLATED (disconnected) form and the joins break. For RTL/cursive, split by WORD or LINE instead, or exclude cursive text from per-character animation.

Run \`npx kashida .\` before finishing — it must report zero issues. Add \`--render\` to prove the font actually shapes the text (no tofu / fake-Arabic).
`;

const HELP = `kashida v${VERSION} — catch the typography mistakes that break complex-script rendering.
Part of Otto · dev.ottospace.co  (formerly arabitype)

Usage:
  npx kashida [path]                report issues (static tier; default path .)
  npx kashida [path] --json         machine-readable (CI)
  npx kashida [path] --check        exit non-zero if anything found (CI)
  npx kashida [path] --render       + HarfBuzz: shape the text, report tofu /
                                    fake-Arabic-font / unattached marks
  npx kashida [path] --render --font <path>   shape against a specific font file
  npx kashida --url <URL> [--render]  inspect the LIVE rendered page (Chromium;
                                    falls back to curl+shape if Playwright is absent)
  npx kashida [path] --init-rules   write typography rules for your AI agent
  npx kashida [path] --font-fix     generate the scoped Arabic-font fix CSS
                                    (real Arabic font + kills join-shattering letter-spacing)
  npx kashida --help | --version

It reports, it never edits — typography is judgment. Every check is gated on an
actual complex script being present, and per-family: Hebrew / CJK never get a
false letter-spacing flag (they don't join). A pure-Latin file reports nothing.

Config (kashida.config.json): { "arabicFonts": [...], "disable": ["small-size"], "ignore": ["legacy/"] }
Inline: // kashida-ignore (this line + next), // kashida-ignore-file (whole file).`;

const rel = f => { try { return path.relative(process.cwd(), f) || f; } catch { return f; } };

// ── font-fix tier: generate the scoped Arabic/RTL font fix (productizes the ottospace.co/ar fix) ──
const FONT_FIX_FILE = 'kashida-arabic-fallback.css';
const FONT_FIX_CSS = `/*
 * Arabic / RTL font fallback — generated by \`kashida --font-fix\`.
 * Fixes the two most common causes of "Arabic looks broken":
 *   (1) no Arabic-capable font  → letters render as tofu or in a Latin face;
 *   (2) Latin letter-spacing / tracking  → shatters the cursive joins.
 * Import this AFTER your main stylesheet. For production, self-host the font
 * (\`npm i @fontsource/ibm-plex-sans-arabic\`) instead of the CDN @import below.
 */
@import url("https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&display=swap");

:lang(ar), [lang="ar"], [dir="rtl"],
[lang="ar"] *, [dir="rtl"] * {
  font-family: "IBM Plex Sans Arabic", "Cairo", "Noto Sans Arabic", system-ui, sans-serif;
  letter-spacing: normal; /* never letter-space Arabic — it breaks the joins */
}
:lang(ar), [lang="ar"], [dir="rtl"] {
  line-height: 1.7; /* Arabic sits taller; give it room to breathe */
}
`;
function runFontFix(target, o) {
  let outDir = '.';
  try { outDir = fs.statSync(target).isDirectory() ? target : path.dirname(target); } catch {}
  const dest = path.join(outDir, FONT_FIX_FILE);
  fs.writeFileSync(dest, FONT_FIX_CSS);
  if (o.json) { console.log(JSON.stringify({ wrote: dest })); return; }
  console.log(`✓ wrote ${rel(dest)} — the Arabic/RTL font fix (scoped @font-face + kills the Latin letter-spacing that shatters joins).`);
  console.log(`  @import it AFTER your main stylesheet, then run \x1b[1mkashida ${target}\x1b[0m to confirm the 'latin-font-stack' issue is gone.`);
  console.log(`  production: self-host with \x1b[1mnpm i @fontsource/ibm-plex-sans-arabic\x1b[0m instead of the CDN @import.`);
}

// ── static tier ─────────────────────────────────────────────────────────────
async function runStatic(target, opts, o) {
  let files;
  try { files = fs.statSync(target).isDirectory() ? walk(target) : [target]; }
  catch { console.error(`kashida: cannot read ${target}`); process.exit(2); }
  const ignoreGlobs = opts.ignoreGlobs || [];
  if (ignoreGlobs.length) files = files.filter(f => !ignoreGlobs.some(g => f.includes(g)));

  const byFile = {}; let total = 0, renderTotal = 0;

  let shapeCore = null, refFont = null;
  if (o.render) {
    try { shapeCore = require('../lib/shape-core'); } catch { shapeCore = null; }
    if (shapeCore && !(await shapeCore.isAvailable())) shapeCore = null;
    if (o.font) { try { refFont = fs.readFileSync(o.font); } catch { console.error(`kashida: cannot read font ${o.font}`); } }
    if (!refFont && shapeCore) refFont = shapeCore.referenceFontBytes();
    if (o.render && !shapeCore) console.error('kashida: --render needs harfbuzzjs (optionalDependency). Skipping the shape tier.');
  }

  for (const file of files) {
    let src; try { src = fs.readFileSync(file, 'utf8'); } catch { continue; }
    const { findings } = scanSource(file, src, opts);
    let all = findings.slice();
    if (o.render && shapeCore && refFont) {
      const runs = shapeCore.extractRuns(src, 300);
      for (const r of runs) {
        try {
          const rf = await shapeCore.analyze(refFont, r.text, { fontName: o.font ? path.basename(o.font) : 'Amiri (reference)', label: r.text.slice(0, 24) });
          for (const f of rf) { all.push({ rule: f.rule, sev: 'render', line: lineAt(src, r.index), from: f.from, to: '', msg: f.msg }); renderTotal++; }
        } catch {}
      }
    }
    if (all.length) { all.sort((a, b) => a.line - b.line || a.rule.localeCompare(b.rule)); byFile[file] = all; total += findings.length; }
  }

  if (o.json) {
    console.log(JSON.stringify({
      version: VERSION, tier: o.render ? 'static+render' : 'static', files: files.length,
      flags: total, renderFlags: renderTotal,
      findings: Object.entries(byFile).flatMap(([f, arr]) => arr.map(x => ({ file: rel(f), ...x }))),
    }, null, 2));
    process.exit(total + renderTotal ? 1 : 0);
  }

  for (const file of Object.keys(byFile)) {
    console.log(`\n\x1b[1m${rel(file)}\x1b[0m`);
    for (const f of byFile[file]) {
      const tag = f.sev === 'render' ? '\x1b[33mrender\x1b[0m' : '\x1b[35mtype\x1b[0m';
      console.log(`  ${tag} :${f.line}  ${f.rule}  \x1b[2m${f.msg}\x1b[0m`);
    }
  }
  const grand = total + renderTotal;
  console.log(`\n\x1b[1mkashida v${VERSION}\x1b[0m  ${files.length} files  ·  \x1b[35m${total} type\x1b[0m${o.render ? `  ·  \x1b[33m${renderTotal} render\x1b[0m` : ''}`);
  if (!grand) console.log('✓ clean — nothing that would break complex-script type.');
  else console.log('→ fix for the script in play; run \x1b[1m--init-rules\x1b[0m so your AI agent stops adding them.');
  process.exit(grand ? 1 : 0);
}

// ── live / url tier ─────────────────────────────────────────────────────────
async function runUrl(url, o) {
  let live; try { live = require('../lib/live-core'); } catch { console.error('kashida: live tier module missing'); process.exit(2); }
  let font = null;
  if (o.font) { try { font = fs.readFileSync(o.font); } catch { console.error(`kashida: cannot read font ${o.font}`); } }

  let result = null;
  const canPlaywright = await live.isAvailable();
  if (canPlaywright) {
    try { result = await live.run(url, { render: o.render, font, screenshot: false }); }
    catch (e) { console.error(`kashida: Playwright run failed (${e.message}) — falling back to curl.`); }
  } else {
    console.error('kashida: Playwright not installed — using curl+shape fallback (install: npm i -D playwright && npx playwright install chromium).');
  }
  if (!result) {
    try { result = await live.curlAnalyze(url, { font }); }
    catch (e) { console.error(`kashida: could not fetch ${url}: ${e.message}`); process.exit(2); }
  }

  const findings = result.findings || [];
  if (o.json) { console.log(JSON.stringify({ version: VERSION, tier: 'live', ...result }, null, 2)); process.exit(findings.length ? 1 : 0); }

  console.log(`\n\x1b[1m${url}\x1b[0m  \x1b[2m(${result.path})\x1b[0m`);
  if (!findings.length) { console.log('✓ clean — no render-time complex-script issues found.'); process.exit(0); }
  for (const f of findings) {
    const where = f.selector ? `\x1b[2m${f.selector}\x1b[0m` : '';
    const sc = f.scripts && f.scripts.length ? `\x1b[2m[${f.scripts.join(',')}]\x1b[0m ` : '';
    console.log(`\n  \x1b[33m${f.rule}\x1b[0m  ${where}`);
    if (f.text) console.log(`    \x1b[2mtext:\x1b[0m ${sc}${String(f.text).slice(0, 70)}`);
    if (f.evidence) console.log(`    \x1b[2mevidence:\x1b[0m ${JSON.stringify(f.evidence)}`);
    if (f.fix) console.log(`    \x1b[2mfix:\x1b[0m ${f.fix}`);
  }
  console.log(`\n\x1b[1mkashida v${VERSION}\x1b[0m  ${url}  ·  \x1b[33m${findings.length} render issue${findings.length === 1 ? '' : 's'}\x1b[0m`);
  process.exit(findings.length ? 1 : 0);
}

async function main() {
  const o = parseArgs(process.argv.slice(2));
  if (o.help) { console.log(HELP); return; }
  if (o.version) { console.log(VERSION); return; }
  const target = o._[0] || '.';

  if (o.initRules) {
    const dest = path.join(fs.existsSync(target) && fs.statSync(target).isDirectory() ? target : '.', 'ARABIC-TYPE-RULES.md');
    fs.writeFileSync(dest, RULES_DOC);
    console.log(`✓ wrote ${dest} — point Cursor/Claude at it so they stop breaking complex-script type.`);
    return;
  }

  if (o.fontFix) { runFontFix(target, o); return; }

  if (o.url) return runUrl(o.url, o);

  const cfg = loadConfig(target);
  const opts = { arabicFonts: cfg.arabicFonts, disable: cfg.disable, ignoreGlobs: Array.isArray(cfg.ignore) ? cfg.ignore : [] };
  return runStatic(target, opts, o);
}

main().catch(e => { console.error('kashida: ' + (e && e.stack || e)); process.exit(2); });
