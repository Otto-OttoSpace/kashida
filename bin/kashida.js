#!/usr/bin/env node
'use strict';
/*
 * kashida — catch the Arabic-typography mistakes that quietly break Arabic
 * rendering, but ONLY where Arabic is actually in play.
 *
 * Arabic is a connected, cursive script that carries diacritics (tashkeel):
 *  - letter-spacing / tracking SHATTERS its ligatures & joins
 *  - tight line-height CRUSHES the tashkeel
 *  - small sizes hurt its dense legibility
 *  - text-transform: uppercase is meaningless (Arabic has no case)
 *  - Latin-only fonts render Arabic in an ugly fallback
 * AI codegen (Western-default styling) does all five. kashida detects them via
 * a real parser (Babel / PostCSS) and reports — it never edits, because
 * typography is a judgment call. (Formerly published as `arabitype`.)
 */
const fs = require('fs');
const path = require('path');
const { scanSource } = require('../lib/kashida-core');

const VERSION = require('../package.json').version;

const CODE_EXT = new Set(['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.html', '.htm', '.vue', '.svelte', '.astro']);
const CSS_EXT = new Set(['.css', '.scss', '.less', '.pcss']);
const IGNORE_DIR = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'out', 'coverage', '.turbo', 'vendor', '.svelte-kit']);

function walk(dir, out = []) {
  let entries;
  try { entries = fs.readdirSync(dir); } catch { return out; }
  for (const name of entries) {
    if (IGNORE_DIR.has(name) || (name.startsWith('.') && name !== '.')) continue;
    const full = path.join(dir, name);
    let st; try { st = fs.statSync(full); } catch { continue; }
    if (st.isDirectory()) walk(full, out);
    else {
      const ext = path.extname(full);
      if (CODE_EXT.has(ext) || CSS_EXT.has(ext)) out.push(full);
    }
  }
  return out;
}

function loadConfig(target) {
  let dir;
  try { dir = fs.statSync(target).isDirectory() ? target : path.dirname(target); }
  catch { dir = process.cwd(); }
  for (const base of [dir, process.cwd()]) {
    for (const name of ['kashida.config.json', '.kashidarc.json', '.kashidarc']) {
      const p = path.join(base, name);
      try { if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8')); } catch {}
    }
  }
  return {};
}

const RULES_DOC = `# Arabic typography rules for AI coding agents (generated by kashida)
When styling anything that can hold Arabic text:
1. NEVER apply letter-spacing / Tailwind tracking-* to Arabic — it shatters the cursive joins & ligatures. Keep it 0/normal.
2. Give Arabic room: line-height ≥ 1.5 (never leading-none/tight/snug) so tashkeel (diacritics) don't collide.
3. Arabic body text ≥ 16px (avoid text-xs/text-sm for body).
4. Never text-transform: uppercase on Arabic — it has no case; it does nothing and hides bugs.
5. Use an Arabic-capable font with a real fallback (e.g. "Cairo","IBM Plex Sans Arabic", system-ui) — never a Latin-only stack for Arabic.

Run \`npx kashida .\` before finishing — it must report zero Arabic-type issues.
`;

const HELP = `kashida v${VERSION} — catch the Arabic-typography mistakes that break Arabic rendering.
Part of Otto · dev.ottospace.co  (formerly arabitype)

Usage:
  npx kashida [path]             report Arabic-typography issues (default: .)
  npx kashida [path] --json      machine-readable (CI)
  npx kashida [path] --check     report only, exit non-zero if anything found (CI)
  npx kashida [path] --init-rules  write ARABIC-TYPE-RULES.md for your AI agent
  npx kashida --help | --version

It reports, it never edits — typography is judgment. It flags where Arabic would
break (tracking, tight leading, tiny sizes, uppercase, Latin-only fonts) and ONLY
where Arabic is actually present (Arabic glyphs, lang="ar"/dir="rtl", or an
.arabic/[lang=ar] selector) — a pure-Latin file reports nothing.

Config (kashida.config.json): { "arabicFonts": [...], "disable": ["small-size"], "ignore": ["legacy/"] }
Inline: // kashida-ignore (this line + next), // kashida-ignore-file (whole file).`;

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) { console.log(HELP); return; }
  if (args.includes('--version') || args.includes('-v')) { console.log(VERSION); return; }
  const asJson = args.includes('--json');
  // --check is documented for CI; report-only already exits non-zero on any finding.
  const target = args.find(a => !a.startsWith('-')) || '.';

  if (args.includes('--init-rules')) {
    const dest = path.join(fs.existsSync(target) && fs.statSync(target).isDirectory() ? target : '.', 'ARABIC-TYPE-RULES.md');
    fs.writeFileSync(dest, RULES_DOC);
    console.log(`✓ wrote ${dest} — point Cursor/Claude at it so they stop breaking Arabic type.`);
    return;
  }

  const cfg = loadConfig(target);
  const opts = { arabicFonts: cfg.arabicFonts, disable: cfg.disable };
  const ignoreGlobs = Array.isArray(cfg.ignore) ? cfg.ignore : [];

  let files;
  try { files = fs.statSync(target).isDirectory() ? walk(target) : [target]; }
  catch { console.error(`kashida: cannot read ${target}`); process.exit(2); }
  if (ignoreGlobs.length) files = files.filter(f => !ignoreGlobs.some(g => f.includes(g)));

  const byFile = {}; let total = 0;
  for (const file of files) {
    let src; try { src = fs.readFileSync(file, 'utf8'); } catch { continue; }
    const { findings } = scanSource(file, src, opts);
    if (findings.length) { byFile[file] = findings; total += findings.length; }
  }
  const rel = f => path.relative(process.cwd(), f) || f;

  if (asJson) {
    console.log(JSON.stringify({
      version: VERSION, files: files.length, flags: total,
      findings: Object.entries(byFile).flatMap(([f, arr]) => arr.map(x => ({ file: rel(f), ...x }))),
    }, null, 2));
    process.exit(total ? 1 : 0);
  }

  for (const file of Object.keys(byFile)) {
    console.log(`\n\x1b[1m${rel(file)}\x1b[0m`);
    for (const f of byFile[file]) console.log(`  \x1b[35mtype\x1b[0m :${f.line}  ${f.from}  \x1b[2m${f.msg}\x1b[0m`);
  }
  console.log(`\n\x1b[1mkashida v${VERSION}\x1b[0m  ${files.length} files  ·  \x1b[35m${total} Arabic-type issue${total === 1 ? '' : 's'}\x1b[0m`);
  if (!total) console.log('✓ clean — nothing that would break Arabic type.');
  else console.log('→ fix for Arabic text; run \x1b[1m--init-rules\x1b[0m so your AI agent stops adding them.');
  process.exit(total ? 1 : 0);
}

main();
